// 輔助函數：用簡單的 hash 演算法，讓同一首歌曲/變數值始終對應到同一個高度關聯的反思語句，保持確定性
function getDeterministicIndex(seed: string, max: number): number {
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = seed.charCodeAt(i) + ((hash << 5) - hash);
  }
  return Math.abs(hash) % max;
}

